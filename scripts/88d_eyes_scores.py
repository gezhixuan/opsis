#!/usr/bin/env python
"""Score the looking runs of scripts/100 (local VLMs and gpt-6-sol with a thumbnail and six tiles) and the gpt-6-sol looking run of
scripts/81 on the full split composites: accuracy per operator, AUROC of P(yes) on the binary transfer rows (CAMELYON16
metastasis, BCSS necrosis), majority class. Writes results/organiser/eyes_scores.json {model: {qset: {op: {n, acc, auroc}}}}
and results/collected/RESULTS_vlm_eyes.md. Runs are found by name: eyes_<model>_<qset>[_s<i>].jsonl and sol_vision_pan_composites_s<i>.jsonl.
    python scripts/88d_eyes_scores.py"""
import json, glob, os, re, sys, collections
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
from opsis import paths
OUT = f"{paths.ROOT}/results/organiser"; MODELS = {"qwen3vl8b": "Qwen3-VL-8B", "pathor1": "Patho-R1-7B", "sol": "gpt-6-sol", "opus55": "Claude Opus 5.5"}
def rows_of(pattern): return [json.loads(l) for f in sorted(glob.glob(f"{OUT}/{pattern}")) for l in open(f)]
def auroc(y, s):
    from sklearn.metrics import roc_auc_score
    y = np.asarray(y); s = np.asarray(s, float); ok = np.isfinite(s)
    return float(roc_auc_score(y[ok], s[ok])) if ok.sum() > 1 and 0 < y[ok].sum() < ok.sum() else None
def score(rows):
    by = collections.defaultdict(list)
    for r in rows: by[r["operator"]].append(r)
    out = {}
    for op, rs in by.items():
        y = [r["answer"] for r in rs]; pred = [r.get("pred") for r in rs]
        maj = max(collections.Counter(y).values()) / len(rs)
        d = dict(n=len(rs), acc=round(sum(p == t for p, t in zip(pred, y)) / len(rs), 4), majority=round(maj, 4), no_answer=sum(p is None for p in pred))
        if all(r.get("probs") and len(r["probs"]) == 2 for r in rs if r.get("probs")) and set(y) <= {0, 1}:
            s = [r["probs"][1] if r.get("probs") else np.nan for r in rs]; au = auroc(y, s)
            if au is not None: d["auroc"] = round(au, 4)
        out[op] = d
    return out
res = collections.defaultdict(dict)
for f in glob.glob(f"{OUT}/eyes_*_*.jsonl"):
    m = re.match(r"eyes_(qwen3vl8b|pathor1|sol|opus55)_(pan|brca|camelyon|bcss|nucls)(_s\d+)?\.jsonl", os.path.basename(f))
    if not m: continue
    model, qset = m.group(1), m.group(2)
    if qset in res[model]: continue
    res[model][qset] = score(rows_of(f"eyes_{model}_{qset}*.jsonl"))
comp = rows_of("sol_vision_pan_composites_s?.jsonl")
if comp:
    res["sol"].setdefault("pan", {}).update(score(comp))
    allc = score([dict(r, operator="all_composites") for r in comp])["all_composites"]; res["sol"]["pan"]["all_composites"] = allc
for model in list(res):
    for qset in list(res[model]):
        rs = [r for r in rows_of(f"eyes_{model}_{qset}*.jsonl") if r["operator"] in ("high_grade_and_lvi", "necrosis_and_high_mitotic", "grade_from_components", "precursor_type", "dcis_with_comedo")]
        if qset == "pan" and rs and "all_composites" not in res[model][qset]: res[model][qset]["all_composites"] = score([dict(r, operator="all_composites") for r in rs])["all_composites"]
json.dump(res, open(f"{OUT}/eyes_scores.json", "w"), indent=1)
L = ["# Vision language models with their own eyes on the slide level rows (generated by scripts/88d_eyes_scores.py)", "",
     "A 1024 px thumbnail and six random 256 um tissue tiles at 0.5 um per pixel per slide (the eyes condition of scripts/81), no label of the task. Local models score the option letters by the next token logits (scripts/100); gpt-6-sol and Claude Opus 5.5 answer in JSON with a confidence, used as the score for AUROC. BCSS: one 128 um tile, necrosis positive when at least half the mask is necrosis or debris. CAMELYON16: the official 129 slide test set.", ""]
for model, M in res.items():
    L += [f"## {MODELS[model]}", "", "| set | operator | n | majority | accuracy | AUROC | no answer |", "|---|---|---|---|---|---|---|"]
    for qset, ops in M.items():
        for op, d in ops.items(): L.append(f"| {qset} | {op} | {d['n']} | {d['majority']:.3f} | {d['acc']:.3f} | {d.get('auroc', '')} | {d['no_answer']} |")
    L.append("")
open(f"{paths.ROOT}/results/collected/RESULTS_vlm_eyes.md", "w").write("\n".join(L) + "\n"); print("\n".join(L[3:]))
