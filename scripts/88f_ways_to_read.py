#!/usr/bin/env python
"""Three ways for a frontier model to read a slide, on the organiser question set (the 189 questions about 29 TCGA-BRCA test
slides of scripts/88b): it reads a written description (the PRISM2 report, or the description Claude Opus 5.5 writes of 6 or 48 tiles, scripts/106; gpt-6-sol reads the same cached texts),
it looks (a thumbnail and six prescribed tiles, grey images of the same sizes as the control of that condition, or regions of its own choice: scripts/81 --arm vision, --blank-image, --arm look for Claude,
the Codex run codex_sol_vision for gpt-6-sol), or it asks
typed questions of Opsis-S (scripts/81 --arm tools). Per condition: accuracy, the paired slide bootstrap interval of asking
minus the condition, input tokens per question, the length and cost of the description, views per question, accuracy per
operator. Reads results/organiser/*.jsonl only, the majority class comes from comparables_brca30.json (scripts/88b).
Writes results/organiser/ways_brca30.json and results/collected/RESULTS_ways_to_read.md.
    python scripts/88f_ways_to_read.py"""
import json, glob, os, re, collections
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); ORG = f"{ROOT}/results/organiser"
os.makedirs(f"{ROOT}/results/collected", exist_ok=True)
# model -> [(way, condition, file pattern)], the first condition of a model is the one the others are paired against
RUNS = {
    "Claude Opus 5.5": [("ask", "asks Opsis-S", "opus55_tools_brca30.jsonl"),
                        ("look", "looks at a thumbnail and six tiles", "opus55_vision_brca30.jsonl"),
                        ("look", "looks at views of its own choice", "opus55_look_brca30_s?.jsonl"),
                        ("read", "reads the PRISM2 report", "prism2report_brca30.jsonl"),
                        ("read", "reads its own description of 6 tiles", "opus55_describe6_brca30_s?.jsonl"),
                        ("read", "reads its own description of 48 tiles", "opus55_describe48_brca30_s?.jsonl")],
    "gpt-6-sol": [("ask", "asks Opsis-S", "sol_tools_brca30.jsonl"), ("look", "looks at a thumbnail and six tiles", "sol_vision_brca30.jsonl"),
                  ("look", "looks at grey images in their place", "sol_vision_blank_brca30.jsonl"),          # scripts/81 --arm vision --blank-image: the same prompt, every image replaced by a grey one of its size
                  ("look", "looks at views of its own choice", "codex_sol_vision_brca30.jsonl"),
                  ("read", "reads the PRISM2 report", "sol_prism2report_brca30.jsonl"),
                  ("read", "reads the description of 6 tiles by Claude Opus 5.5", "sol_describe6_brca30.jsonl"),
                  ("read", "reads the description of 48 tiles by Claude Opus 5.5", "sol_describe48_brca30.jsonl")],   # scripts/106 --answer-backend api: the cached text, answered by gpt-6-sol
    "gpt-5.5": [("ask", "asks Opsis-S", "gpt55_tools_brca30.jsonl"), ("look", "looks at a thumbnail and six tiles", "gpt55_vision_brca30.jsonl")],
    "gpt-6-astra": [("ask", "asks Opsis-S", "gpt6astra_tools_brca30.jsonl"), ("look", "looks at a thumbnail and six tiles", "gpt6astra_vision_brca30.jsonl")],
}
VIEW = re.compile(r"'tool': '[^']*view_region'")   # one call = one region chosen by the model (the thumbnail is not counted)


def load(pattern):
    rows = {}
    for f in sorted(glob.glob(f"{ORG}/{pattern}")):
        for l in open(f):
            r = json.loads(l); rows[r["qid"]] = r          # a resumed shard may repeat a question, the last answer counts
    return rows


def boot(a, b, slides, n=10000, seed=0):
    """paired bootstrap over slides of mean(a) - mean(b), a and b are correctness vectors over the same questions"""
    rng = np.random.default_rng(seed); u = sorted(set(slides)); idx = {s: np.flatnonzero(np.asarray(slides) == s) for s in u}
    d = []
    for _ in range(n):
        pick = np.concatenate([idx[u[i]] for i in rng.integers(0, len(u), len(u))]); d.append(a[pick].mean() - b[pick].mean())
    return float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))


comp = json.load(open(f"{ORG}/comparables_brca30.json")); N = comp["n"]
maj = sum(v["majority"] * v["n"] for v in comp["per_op"].values()) / sum(v["n"] for v in comp["per_op"].values())
res = dict(n=N, majority=round(maj, 4), models={})
L = ["# Three ways for a frontier model to read a slide (generated by scripts/88f_ways_to_read.py)", "",
     f"The {N} questions about TCGA-BRCA test slides of the organiser question set, majority class {maj:.3f}. A model reads a written description of the slide and answers from the text alone, looks at pixels, or asks typed questions of Opsis-S. The interval is the paired bootstrap over slides (10,000 resamples) of asking minus the condition, in points. Input tokens are the mean prompt tokens per question as reported by each backend, description tokens are spent once per slide.", ""]
for model, conds in RUNS.items():
    ref = None; M = []
    for way, name, pattern in conds:
        rows = load(pattern)
        if not rows: print("missing", model, name, pattern); continue
        if ref is None: ref = rows
        q = sorted(set(rows) & set(ref)); slides = [rows[i]["slide"] for i in q]
        c = np.array([bool(rows[i]["correct"]) for i in q], float); cr = np.array([bool(ref[i]["correct"]) for i in q], float)
        d = dict(way=way, condition=name, n=len(rows), complete=len(rows) == N, acc=round(float(np.mean([bool(r["correct"]) for r in rows.values()])), 6),
                 no_answer=sum(r.get("pred") is None for r in rows.values()), input_tokens=round(float(np.mean([r["usage"]["prompt"] for r in rows.values() if r.get("usage")])), 0))
        if rows is not ref:
            lo, hi = boot(cr, c, slides); d.update(ask_minus=round(100 * float(cr.mean() - c.mean()), 1), ci=[round(100 * lo, 1), round(100 * hi, 1)], n_paired=len(q))
        views = [len(VIEW.findall(str(r.get("tools", "")))) for r in rows.values()]
        if way == "look" and sum(views): d["views"] = round(float(np.mean(views)), 1)
        if any("desc_words" in r for r in rows.values()):
            per_slide = {r["slide"]: r for r in rows.values()}                 # the description is written once per slide
            d["desc_words"] = round(float(np.mean([r["desc_words"] for r in per_slide.values()])), 0)
            d["desc_tokens"] = round(float(np.mean([r["desc_usage"]["prompt"] + r["desc_usage"]["completion"] for r in per_slide.values()])), 0)
        by = collections.defaultdict(list)
        for r in rows.values(): by[r["operator"]].append(bool(r["correct"]))
        d["per_op"] = {op: round(float(np.mean(v)), 6) for op, v in sorted(by.items())}
        M.append(d)
    res["models"][model] = M
    L += [f"## {model}", "", "| way | condition | n | accuracy | asking minus this, points | input tokens per question | views per question | description words | description tokens per slide |", "|---|---|---|---|---|---|---|---|---|"]
    for d in M:
        ci = f"{d['ask_minus']:+.1f} [{d['ci'][0]:.1f}, {d['ci'][1]:.1f}]" if "ci" in d else ""
        L.append(f"| {d['way']} | {d['condition']} | {d['n']} | {d['acc']:.3f} | {ci} | {d['input_tokens']:.0f} | {d.get('views', '')} | {d.get('desc_words', '')} | {d.get('desc_tokens', '')} |")
    L.append("")
ops = sorted({op for M in res["models"].values() for d in M for op in d["per_op"]})
M = res["models"]["Claude Opus 5.5"]
L += ["## Claude Opus 5.5, accuracy per operator", "", "| operator | n | majority | " + " | ".join(d["condition"] for d in M) + " |", "|---|---|---|" + "---|" * len(M)]
for op in ops:
    L.append(f"| {op} | {comp['per_op'][op]['n']} | {comp['per_op'][op]['majority']:.2f} | " + " | ".join(f"{d['per_op'].get(op, float('nan')):.2f}" for d in M) + " |")
# ---- the whole test split: the 12 operators of scripts/106 on every test slide (no pan_infiltrate), paired on the question ids ----
PAN = [("ask", "Claude Opus 5.5 asks Opsis-S", ["opus55_tools_pan_alias_composites_s?.jsonl", "opus55_tools_pan_synoptic_s?.jsonl"]),
       ("ask", "gpt-6-sol asks Opsis-S", ["sol_tools_pan_alias_composites_s?.jsonl", "sol_tools_pan_alias_synoptic_s?.jsonl"]),
       ("read", "gpt-6-sol reads the PRISM2 report", ["sol_prism2report_pan_s?.jsonl"])]
COMPOSITES = ["high_grade_and_lvi", "necrosis_and_high_mitotic", "grade_from_components", "dcis_with_comedo", "precursor_type"]
P = {name: {k: v for pat in pats for k, v in load(pat).items()} for _, name, pats in PAN}; P = {k: v for k, v in P.items() if v}
if "gpt-6-sol reads the PRISM2 report" in P:
    base = P["gpt-6-sol reads the PRISM2 report"]; pan = dict(n=len(base), n_slides=len({r["slide"] for r in base.values()}), conditions={}, pairs=[])
    # the majority class of an operator is its most frequent answer among these test questions, a family's is the n weighted mean over its operators
    gold = collections.defaultdict(list)
    for r in base.values(): gold[r["operator"]].append(str(r["answer"]))
    pan["per_op"] = {o: dict(n=len(g), majority=round(collections.Counter(g).most_common(1)[0][1] / len(g), 6)) for o, g in sorted(gold.items())}
    fam = lambda ops: round(sum(pan["per_op"][o]["majority"] * pan["per_op"][o]["n"] for o in ops) / max(sum(pan["per_op"][o]["n"] for o in ops), 1), 6)
    pan["majority"] = dict(all=fam(list(gold)), composites=fam([o for o in gold if o in COMPOSITES]), synoptic=fam([o for o in gold if o not in COMPOSITES]))
    L += ["", "## The whole test split", "", f"The same 12 operators on every test slide: {len(base)} questions about {pan['n_slides']} slides, majority class {pan['majority']['all']:.3f} (composites {pan['majority']['composites']:.3f}, synoptic {pan['majority']['synoptic']:.3f}). "
          "The interval is the paired bootstrap over slides (10,000 resamples) of the first condition minus the second, in points.", "",
          "| condition | n | accuracy | composites | synoptic | input tokens per question |", "|---|---|---|---|---|---|"]
    for name, R in P.items():
        q = sorted(set(R) & set(base)); acc = lambda ks: float(np.mean([bool(R[k]["correct"]) for k in ks])) if ks else float("nan")
        co = [k for k in q if R[k]["operator"] in COMPOSITES]; sy = [k for k in q if R[k]["operator"] not in COMPOSITES]
        by = collections.defaultdict(list)
        for k in q: by[R[k]["operator"]].append(bool(R[k]["correct"]))
        tok = round(float(np.mean([R[k]["usage"]["prompt"] for k in q if R[k].get("usage")])), 0)
        pan["conditions"][name] = dict(n=len(q), complete=len(q) == len(base), acc=round(acc(q), 6), composites=round(acc(co), 6), synoptic=round(acc(sy), 6), input_tokens=tok, per_op={o: round(float(np.mean(v)), 6) for o, v in sorted(by.items())})
        L.append(f"| {name} | {len(q)} | {acc(q):.3f} | {acc(co):.3f} | {acc(sy):.3f} | {tok:.0f} |")
    L += ["", "| first minus second | n | all | composites | synoptic | same answer |", "|---|---|---|---|---|---|"]
    def diff(A, B, keep):
        q = sorted(k for k in set(P[A]) & set(P[B]) & set(base) if keep(P[A][k]["operator"]))      # the 12 operators only: both organiser runs also asked pan_infiltrate
        if not q: return dict(n=0), ""                                                    # a run still in progress has no question of this family yet
        x = np.array([bool(P[A][k]["correct"]) for k in q], float); y = np.array([bool(P[B][k]["correct"]) for k in q], float)
        lo, hi = boot(x, y, [P[A][k]["slide"] for k in q]); d = dict(n=len(q), diff=round(100 * float(x.mean() - y.mean()), 1), ci=[round(100 * lo, 1), round(100 * hi, 1)])
        return d, f"{d['diff']:+.1f} [{d['ci'][0]:.1f}, {d['ci'][1]:.1f}]"
    for A, B in [("Claude Opus 5.5 asks Opsis-S", "gpt-6-sol reads the PRISM2 report"), ("gpt-6-sol asks Opsis-S", "gpt-6-sol reads the PRISM2 report"), ("Claude Opus 5.5 asks Opsis-S", "gpt-6-sol asks Opsis-S")]:
        if A not in P or B not in P: continue
        cells = []; row = dict(first=A, second=B)
        for lab, keep in [("all", lambda o: True), ("composites", lambda o: o in COMPOSITES), ("synoptic", lambda o: o not in COMPOSITES)]:
            row[lab], c = diff(A, B, keep); cells.append(c)
        q = sorted(set(P[A]) & set(P[B]) & set(base)); row["same_answer"] = round(float(np.mean([str(P[A][k].get("pred")) == str(P[B][k].get("pred")) for k in q])), 6)
        if A.split(" asks")[0] == B.split(" reads")[0]: row["per_op"] = {o: diff(A, B, lambda x, o=o: x == o)[0] for o in sorted(gold)}      # the same model asking and reading, per operator
        pan["pairs"].append(row); L.append(f"| {A} minus {B} | {row['all']['n']} | " + " | ".join(cells) + f" | {row['same_answer']:.3f} |")
    same = next((r for r in pan["pairs"] if "per_op" in r), None)
    if same:
        names = list(pan["conditions"]); L += ["", f"| operator | n | majority | " + " | ".join(names) + f" | {same['first']} minus {same['second']} |", "|---|---|---|" + "---|" * (len(names) + 1)]
        for o, v in pan["per_op"].items():
            d = same["per_op"][o]; L.append(f"| {o} | {v['n']} | {v['majority']:.3f} | " + " | ".join(f"{pan['conditions'][c]['per_op'].get(o, float('nan')):.3f}" for c in names) + f" | {d['diff']:+.1f} [{d['ci'][0]:.1f}, {d['ci'][1]:.1f}] |")
    res["pan"] = pan
json.dump(res, open(f"{ORG}/ways_brca30.json", "w"), indent=1)
open(f"{ROOT}/results/collected/RESULTS_ways_to_read.md", "w").write("\n".join(L) + "\n"); print("\n".join(L[2:]))
