#!/usr/bin/env python
"""Compare the organiser conditions (results/organiser/<name>_summary.json + .jsonl): accuracy per operator, tool calls, tokens, cost.
    python scripts/82_organiser_table.py --runs structured_brca30,sol_tools_brca30,sol_vision_brca30,sol_both_brca30 [--price-in 2 --price-out 10] [--out results/collected/RESULTS_organiser.md]"""
import argparse, json, os
import numpy as np, pandas as pd
from opsis import paths
ap = argparse.ArgumentParser(); ap.add_argument("--runs", required=True); ap.add_argument("--price-in", type=float, default=None, help="USD per million input tokens"); ap.add_argument("--price-out", type=float, default=None); ap.add_argument("--out", default=None); a = ap.parse_args()
D = f"{paths.ROOT}/results/organiser"; R = {}
for n in a.runs.split(","):
    f = f"{D}/{n}.jsonl"
    if os.path.exists(f): R[n] = pd.DataFrame([json.loads(l) for l in open(f)])
ops = sorted({op for df in R.values() for op in df.operator.unique()}); common = set.intersection(*[set(df.qid) for df in R.values()])
rows = []
for op in ops:
    r = {"operator": op, "n": 0}
    for n, df in R.items():
        g = df[(df.operator == op) & df.qid.isin(common)]; r["n"] = len(g); r[n] = f"{g.correct.mean():.3f}" if len(g) else ""
    rows.append(r)
tot = {"operator": "all (common questions)", "n": len(common)}
for n, df in R.items():
    g = df[df.qid.isin(common)]; tot[n] = f"{g.correct.mean():.3f}"
rows.append(tot)
T = pd.DataFrame(rows); print(T.to_string(index=False))
cost = []
for n, df in R.items():
    g = df[df.qid.isin(common)]; pi = sum(u["prompt"] for u in g.usage); po = sum(u["completion"] for u in g.usage)
    c = dict(run=n, questions=len(g), tool_calls_per_q=round(float(g.steps.mean()), 2), input_tokens_per_q=int(pi / max(len(g), 1)), output_tokens_per_q=int(po / max(len(g), 1)), seconds_per_q=round(float(g.seconds.mean()), 1))
    if a.price_in is not None: c["usd_per_q"] = round((pi * a.price_in + po * (a.price_out or 0)) / 1e6 / max(len(g), 1), 4)
    cost.append(c)
C = pd.DataFrame(cost); print(C.to_string(index=False))
if a.out:
    md = ["# Organiser arms on the pan TCGA test slides (generated by scripts/82_organiser_table.py)", "", "Accuracy per operator on the questions all arms answered. structured = the slide readout alone with rule composition (no language model); tools = the language model answering through the typed readouts; vision = the language model looking at a thumbnail and six 256 um tiles; both = vision plus the tools and view_region.", "",
          "| " + " | ".join(T.columns) + " |", "|" + "---|" * len(T.columns), *("| " + " | ".join(str(x) for x in r) + " |" for r in T.itertuples(index=False)), "", "| " + " | ".join(C.columns) + " |", "|" + "---|" * len(C.columns), *("| " + " | ".join(str(x) for x in r) + " |" for r in C.itertuples(index=False))]
    open(a.out, "w").write("\n".join(md) + "\n"); print("written", a.out)
